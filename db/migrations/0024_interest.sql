-- 8.  Vocabulary
-- ---------------------------------------------------------------------

-- WHICH SIDE OF THE BOOK TODAY LANDS ON, derived from the sign of the
-- balance and from nothing else. Not a product, not a customer choice,
-- not a column somebody sets: interest_side_of(balance) is a function.
--
-- 'flat' is a real state and it is not an error -- a deposit account at
-- exactly zero owes nothing and is owed nothing. It always decides
-- 'skipped', because postEntry() refuses a zero-amount line and is right
-- to.
CREATE TYPE interest_side AS ENUM ('credit', 'overdraft', 'flat');

COMMENT ON TYPE interest_side IS
  'credit = the customer is in credit and we PAY (5400 debit, deposit credit). overdraft = the customer is in debit and we CHARGE (deposit debit, 4400 credit). flat = a zero balance, which prices at nothing.';

-- WHICH WAY §12.2 WENT, recorded per posting rather than inferred later.
-- 'tie_to_even' is the only one of the four that half-up would have got
-- different, so it is the label worth being able to grep for.
CREATE TYPE interest_rounding AS ENUM ('exact', 'down', 'up', 'tie_to_even');

COMMENT ON TYPE interest_rounding IS
  'How the exact fraction became a cent amount. exact = it divided. down/up = the ordinary cases. tie_to_even = the fraction was exactly a half cent and DESIGN §12.2 broke it to the even cent -- the only case where half-up would have given a different answer.';


-- ---------------------------------------------------------------------
-- 9.  The arithmetic, as IMMUTABLE integer functions
-- ---------------------------------------------------------------------
--
-- These ARE the rounding rule. Every operand and every result is bigint
-- or a small int. There is no numeric, no float, no division that is not
-- integer division, and no intermediate that holds a fraction. IMMUTABLE
-- so a CHECK constraint may call them, which is the point: TypeScript
-- computes the same integers and the database refuses to store any other
-- answer.

-- D = 10000 * day_count. 10000 because a rate is in BASIS POINTS, which
-- is how a rate is stored integer-scaled: 150 bps is 1.50% and is the
-- integer 150, never 0.015.
CREATE FUNCTION interest_denominator(p_day_count int) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT 10000::bigint * p_day_count
$$;

-- N = |balance| * rate_bps. The MAGNITUDE, always >= 0 -- the sign is
-- carried by interest_side_of and applied when the entry is built, so
-- the rounding below cannot be asymmetric in the sign.
--
-- Overflow is a loud failure rather than a silent wrap: bigint tops out
-- at 9.22e18, so this raises above roughly $9.2 trillion at 100% a year.
-- A rate is CHECKed <= 10000 bps on every table that stores one, which
-- is what keeps that bound where it is.
CREATE FUNCTION interest_numerator(p_balance_cents bigint, p_rate_bps int) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT abs(p_balance_cents) * p_rate_bps::bigint
$$;

-- DESIGN §12.2, in five lines of integer arithmetic.
--
--   q = N div D,  r = N mod D,  both non-negative
--   2r > D  -> the fraction is past a half: round up
--   2r < D  -> short of a half: round down
--   2r = D  -> EXACTLY a half: round to the EVEN cent, i.e. up iff q is
--              odd. `q % 2` is 1 for odd q and 0 for even q, so the
--              whole tiebreak is one modulo and no branch.
--
-- Comparing 2r against D rather than r against D/2 is deliberate: D/2 on
-- integers would truncate for an odd D and would silently classify some
-- genuine ties as 'down'.
CREATE FUNCTION interest_round_half_even(p_num bigint, p_den bigint) RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT (p_num / p_den)
       + CASE
           WHEN 2 * (p_num % p_den) > p_den THEN 1
           WHEN 2 * (p_num % p_den) < p_den THEN 0
           ELSE (p_num / p_den) % 2
         END
$$;

CREATE FUNCTION interest_rounding_of(p_num bigint, p_den bigint) RETURNS interest_rounding
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT CASE
           WHEN p_num % p_den = 0            THEN 'exact'
           WHEN 2 * (p_num % p_den) = p_den  THEN 'tie_to_even'
           WHEN 2 * (p_num % p_den) > p_den  THEN 'up'
           ELSE 'down'
         END::interest_rounding
$$;

-- One day's interest, in cents, as a MAGNITUDE.
CREATE FUNCTION interest_daily_cents(p_balance_cents bigint, p_rate_bps int, p_day_count int)
RETURNS bigint
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT interest_round_half_even(
           interest_numerator(p_balance_cents, p_rate_bps),
           interest_denominator(p_day_count))
$$;

CREATE FUNCTION interest_side_of(p_balance_cents bigint) RETURNS interest_side
LANGUAGE sql IMMUTABLE STRICT AS $$
  SELECT CASE
           WHEN p_balance_cents > 0 THEN 'credit'
           WHEN p_balance_cents < 0 THEN 'overdraft'
           ELSE 'flat'
         END::interest_side
$$;

COMMENT ON FUNCTION interest_round_half_even(bigint, bigint) IS
  'DESIGN §12.2 round-half-to-even on a rational N/D, in integers. The tie goes to the EVEN cent, which is the whole reason §12.2 is half-even rather than half-up: half-up would hand every half-cent to the same party forever.';
COMMENT ON FUNCTION interest_daily_cents(bigint, int, int) IS
  'One business date of interest, as a magnitude in cents: |balance| * rate_bps / (10000 * day_count), rounded half to even. The side (who pays whom) is interest_side_of(balance) and is applied when the journal entry is built.';

ALTER FUNCTION interest_denominator(int)                    SET search_path = public, pg_temp;
ALTER FUNCTION interest_numerator(bigint, int)              SET search_path = public, pg_temp;
ALTER FUNCTION interest_round_half_even(bigint, bigint)     SET search_path = public, pg_temp;
ALTER FUNCTION interest_rounding_of(bigint, bigint)         SET search_path = public, pg_temp;
ALTER FUNCTION interest_daily_cents(bigint, int, int)       SET search_path = public, pg_temp;
ALTER FUNCTION interest_side_of(bigint)                     SET search_path = public, pg_temp;


-- ---------------------------------------------------------------------
-- 10.  The rate card: a tier, and its versions
-- ---------------------------------------------------------------------

-- A named rate card. Exists so a schedule cites something the database
-- can check -- a free-text tier would let a typo enrol an account onto a
-- rate card that has no rows, and every one of its days would then fail
-- at the trigger instead of at the enrolment.
CREATE TABLE interest_rate_tier (
  tier        text PRIMARY KEY CHECK (length(btrim(tier)) > 0),
  description text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- One row per (tier, effective_from). approval_policy's shape, with the
-- two rates that a current account actually has and the day-count
-- convention stated as data.
--
-- BOTH RATES LIVE ON ONE ROW on purpose. A rate card that let the credit
-- rate change on one date and the overdraft rate on another would make
-- "what were our rates on 9 September" a question with two answers and a
-- join. One row, one date, both numbers.
CREATE TABLE interest_rate_policy (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tier                  text NOT NULL REFERENCES interest_rate_tier(tier),
  effective_from        date NOT NULL,

  -- What we PAY on a credit balance. Integer basis points, never a
  -- decimal and never a float: 150 is 1.50% a year.
  credit_rate_bps       integer NOT NULL CHECK (credit_rate_bps BETWEEN 0 AND 10000),
  -- What we CHARGE on a debit balance. Higher, and that is the product,
  -- not an accident -- an arranged business overdraft is expensive money.
  overdraft_rate_bps    integer NOT NULL CHECK (overdraft_rate_bps BETWEEN 0 AND 10000),

  -- §4. ACT/365 fixed is the default and the argued choice; 360 is
  -- permitted so that a money-market product could be priced honestly on
  -- its own convention rather than by quietly scaling a rate.
  day_count_denominator integer NOT NULL DEFAULT 365
                          CHECK (day_count_denominator IN (360, 365)),

  note                  text NOT NULL CHECK (length(btrim(note)) > 0),
  created_by            uuid NOT NULL REFERENCES actor(id),
  created_at            timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT interest_rate_policy_version UNIQUE (tier, effective_from)
);

CREATE INDEX interest_rate_policy_lookup_idx
  ON interest_rate_policy (tier, effective_from DESC);

COMMENT ON TABLE interest_rate_policy IS
  'The rate card, effective-dated and append-only. approval_policy and funds_availability_policy are the pattern; the addition here is a trigger that refuses a row which would re-price a date already accrued.';
COMMENT ON COLUMN interest_rate_policy.day_count_denominator IS
  'ACT/365 fixed by default: Reg DD Appendix A computes the daily periodic rate as the annual rate over 365. 360 would pay and charge 1.389% more a year for the same quoted rate.';


-- THE RULE THAT MAKES "A RATE CHANGE CANNOT RE-PRICE YESTERDAY" A
-- CONSTRAINT RATHER THAN A CONVENTION.
--
-- Two conditions, and the second is the one with teeth:
--
--   (a) effective_from must be later than every existing row for the
--       tier. Rates move forward. Without this, an INSERT with an older
--       date would silently become the resolved rate for a window of
--       past dates.
--
--   (b) effective_from must be later than every date already ACCRUED
--       under this tier. (a) alone is not enough: if the newest policy
--       row is from March and the tick has priced days through
--       September, a row effective in April satisfies (a) and re-prices
--       five months of postings that are already on the ledger.
--
-- Refusing the INSERT is the right remedy rather than detecting it
-- afterwards, because afterwards the postings are immutable and the only
-- repair is a reversal and a re-book of every affected day.
CREATE FUNCTION assert_interest_rate_policy() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_latest date;
  v_priced date;
BEGIN
  SELECT max(p.effective_from) INTO v_latest
    FROM interest_rate_policy p WHERE p.tier = NEW.tier;

  IF v_latest IS NOT NULL AND NEW.effective_from <= v_latest THEN
    RAISE EXCEPTION
      'tier % already has a rate effective %; a rate change is a LATER row, never an earlier or equal one',
      NEW.tier, v_latest USING ERRCODE = '55006';
  END IF;

  SELECT max(d.accrual_date) INTO v_priced
    FROM interest_day d
    JOIN interest_schedule s ON s.id = d.schedule_id
   WHERE s.rate_tier = NEW.tier;

  IF v_priced IS NOT NULL AND NEW.effective_from <= v_priced THEN
    RAISE EXCEPTION
      'tier % has already accrued through %; a rate effective % would retroactively re-price days already on the ledger',
      NEW.tier, v_priced, NEW.effective_from USING ERRCODE = '55006';
  END IF;

  RETURN NEW;
END $$;

ALTER FUNCTION assert_interest_rate_policy() SET search_path = public, pg_temp;

CREATE TRIGGER interest_rate_policy_forward_only
  BEFORE INSERT ON interest_rate_policy
  FOR EACH ROW EXECUTE FUNCTION assert_interest_rate_policy();


-- THE ONLY DEFINITION of "which rate applied on which date": the
-- greatest effective_from that is not after the date. STABLE, not
-- IMMUTABLE -- it reads a table -- so it cannot appear in a CHECK, which
-- is exactly why the posting stores the resolved policy id and a trigger
-- compares the two.
CREATE FUNCTION interest_rate_at(p_tier text, p_date date)
RETURNS interest_rate_policy
LANGUAGE sql STABLE AS $$
  SELECT p.*
    FROM interest_rate_policy p
   WHERE p.tier = p_tier
     AND p.effective_from <= p_date
   ORDER BY p.effective_from DESC
   LIMIT 1
$$;

ALTER FUNCTION interest_rate_at(text, date) SET search_path = public, pg_temp;

COMMENT ON FUNCTION interest_rate_at(text, date) IS
  'The rate card as it stood on a business date. One definition, asked by the tick, by the lifecycle trigger and by v_interest_rate_drift -- so a replay of an old date re-derives the old rate by construction rather than by care.';


-- ---------------------------------------------------------------------
-- 11.  The enrolment
-- ---------------------------------------------------------------------
--
-- One live enrolment per account, enforced by the same kind of gist
-- EXCLUDE constraint 0020 used for prices. Two overlapping enrolments
-- would each claim their own (schedule, date) pairs for the same account
-- and the same day, and the customer would be paid or charged twice with
-- both halves arithmetically perfect.
--
-- There is no product column, because there is no product choice: an
-- account is enrolled in interest, and the sign of its balance on the
-- day decides which side of the book the day lands on.

CREATE TABLE interest_schedule (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- The customer's deposit account. Tenancy is reached through it -- no
  -- business_id column here to drift from account.business_id.
  account_id   uuid NOT NULL REFERENCES account(id),

  -- The rate card, not a rate. See §5.
  rate_tier    text NOT NULL REFERENCES interest_rate_tier(tier),

  currency     char(3) NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),

  start_date   date NOT NULL,
