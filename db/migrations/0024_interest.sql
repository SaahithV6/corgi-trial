-- Every open customer deposit leaf is enrolled. Interest is a property
-- of holding a balance, not of a plan somebody bought -- which is why
-- this is not the three-of-four the platform-fee schedules are.
--
-- start_date is book_date - 4, the same day the rate card opens, so the
-- first tick has five business dates to accrue and the rate change on
-- book_date - 2 falls inside them with days either side.
INSERT INTO interest_schedule
  (account_id, rate_tier, start_date, created_by, schedule_key)
SELECT a.id,
       'standard',
       book_date(now()) - 4,
       act.id,
       'migration:0024:' || a.id::text || ':interest'
  FROM account a
  JOIN actor act ON act.kind = 'system' AND act.display_name = 'ledger-poster'
 WHERE a.code = '2100'
   AND a.business_id IS NOT NULL
   AND a.closed_at IS NULL
ON CONFLICT (schedule_key) DO NOTHING;
