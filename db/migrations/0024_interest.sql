-- =====================================================================
-- 0024  Interest: a price for time and money, not a price for a service
-- =====================================================================
--
-- The other half of the accrual ladder. 0020 built a MONTHLY PLATFORM FEE
-- accrued daily and deliberately did not build interest, for a reason it
-- wrote down and named the missing accounts for (docs/ACCRUAL.md §7):
--
--   "4200 Fee income is what we CHARGE, and interest priced on a balance
--    and a number of days is not a fee for a service."
--
-- This migration adds the two accounts 0020 named -- 4400 Interest income
-- (overdraft) and 5400 Interest expense (credit balances) -- and the
-- daily accrual that posts to them.
--
-- ---------------------------------------------------------------------
-- 1.  WHAT THE BOOK ACTUALLY SHOWS, MEASURED RATHER THAN ASSUMED
-- ---------------------------------------------------------------------
--
-- 0020's author was told the book had overdrawn accounts and corrected
-- the premise: v_overdrawn_accounts returned zero rows. That correction
-- was re-measured before this file was written, at the current booking
-- watermark, and it still holds -- and more strongly than before:
--
--   * v_overdrawn_accounts:                                     0 rows
--   * every deposit leaf, settled balance today:              all > 0
--   * every deposit leaf, settled balance on EVERY value date
--     in the 45-day catch-up window:                          all > 0
--   * every account in the chart, natural balance < 0:          0 rows
--
-- So OVERDRAFT INTEREST SHIPS WITH ZERO ROWS TODAY, and this file says
-- so rather than manufacturing an overdraft to photograph. What ships
-- with rows is CREDIT INTEREST -- what we pay a customer for holding a
-- balance with us -- on four real deposit accounts.
--
-- Both sides are built, because they are not two products. A business
-- current account has a credit rate and an arranged-overdraft rate, and
-- WHICH ONE APPLIES ON A GIVEN DAY IS DECIDED BY THE SIGN OF THE BALANCE
-- ON THAT DAY, not by which product the customer bought. One enrolment,
-- one rate card, two sides. The day an account crosses zero, the same
-- schedule prices the day before on 5400 and the day after on 4400, and
-- nothing has to be reconfigured for that to happen.
--
-- ---------------------------------------------------------------------
-- 2.  WHY THIS IS NOT accrual_product = 'interest' ON 0020's TABLES
-- ---------------------------------------------------------------------
--
-- docs/ACCRUAL.md §7 sketched the extension as
--
--   "an ALTER TYPE accrual_product ADD VALUE 'overdraft_interest', a
--    rate_bps column beside monthly_cents..."
--
-- That was tried first, against this database, and it cannot be done in
-- one migration. Measured, not assumed:
--
--   postgres=# BEGIN;
--   postgres=# ALTER TYPE accrual_product ADD VALUE 'interest';
--   postgres=# SELECT 'interest'::accrual_product;
--   ERROR:  unsafe use of new value "interest" of enum type accrual_product
--
-- PostgreSQL 18.6, and the restriction is documented and permanent: an
-- enum value added by ALTER TYPE cannot be USED until the adding
-- transaction commits. scripts/migrate.mjs applies each file inside one
-- transaction -- correctly, because a half-applied migration is worse
-- than a refused one -- so a single migration can add the value or use
-- it, never both. Splitting across 0024 and 0025 was not available
-- either: this work owns one migration number.
--
-- The second reason is better than the first. `accrual_posting` carries
-- SEVEN stored relations re-derived by `accrual_posting_arithmetic`, and
-- `assert_accrual_posting()` asserts the entry is exactly two lines, a
-- debit to the deposit account and a credit to 4200. Every one of those
-- is fee-shaped. Making them hold interest too would mean nullable
-- columns, a CHECK that branches, and a lifecycle trigger with two arms
-- -- weakening a working proof to avoid writing a second one. So 0020's
-- objects are NOT TOUCHED BY THIS FILE. Nothing here alters a table,
-- replaces a view, or drops a constraint that 0020 created.
--
-- What IS reused is the machinery, which is the thing that mattered:
--
--   * the unit is the (schedule, date) pair          -- 0020 §3
--   * the claim is a UNIQUE row                      -- interest_day
--   * the idempotency key is GENERATED by Postgres
--     from the two source facts                      -- never by the job
--   * the key goes to postEntry(), where
--     journal_entry.idempotency_key is UNIQUE        -- 0001 §12
--   * the row lock is a SECURITY DEFINER function    -- 0008/0012/0020
--   * which dates are owed is ONE SQL function       -- no date maths in TS
--   * the arithmetic is stored AND re-derived by a CHECK
--
-- and, above all, THE SAME TICK. `runAccrual()` runs the fee leg and
-- then the interest leg in one invocation of `/api/cron/accrual`. There
-- is no second scheduler, no second endpoint and no second cron entry.
--
-- The fee leg runs FIRST, deliberately: the fee is a debit dated D, so
-- the end-of-day-D balance that interest is priced on includes it. The
-- ordering is stated because it is observable -- reversing it would move
-- the basis by the fee, which is under a cent of interest but is not
-- nothing, and an ordering that matters should be written down rather
-- than inherited from a loop.
--
-- ---------------------------------------------------------------------
-- 3.  THE ROUNDING RULE: DESIGN §12.2, AND WHY IT IS NOT §12.3
-- ---------------------------------------------------------------------
--
-- research/ledger/DESIGN.md §12 has two rules and the whole skill is
-- knowing which applies:
--
--   §12.2  ONE value -> ONE cent amount:  round HALF TO EVEN.
--   §12.3  ONE amount split across N shares: LARGEST REMAINDER.
--
-- 0020 argued, correctly, that a monthly fee accrued daily is §12.3: the
-- month has a total -- the quoted price -- and the days are shares of
-- it, so the shares must add back up to it exactly, and rounding each
-- day independently bills $24.90 for a $25.00 plan.
--
-- DAILY INTEREST IS §12.2, and the reason is not a preference. §12.3 is
-- not merely worse here, IT IS UNDEFINED: largest-remainder needs a
-- SOURCE AMOUNT to distribute, and daily interest has none. There is no
-- month-total to allocate, because the balance changes every day and the
-- month's interest is not known until the month has happened. You cannot
-- floor N shares of a number you do not have.
--
-- What daily interest IS, exactly, is one value -- a balance, a rate and
-- one day -- becoming one cent amount. That is §12.2's sentence with no
-- interpretation required.
--
--     amount = round_half_even( |balance| * rate_bps / (10000 * 365) )
--
-- HALF TO EVEN AND NOT HALF UP, for §12.2's own stated reason: "half-up
-- biases every tie in one direction, and over a year of interchange that
-- bias is a real number." Here the tie is the half-cent, and half-up
-- would hand it to the same party every time -- to us on an overdraft,
-- to the customer on a credit balance -- forever.
--
-- ROUNDING IS SYMMETRIC IN THE SIGN. The magnitude is rounded and the
-- side is carried separately (interest_side_of), rather than rounding a
-- signed number. Floor division on a negative basis would round every
-- overdraft charge AWAY from zero and every credit payment TOWARD it --
-- a systematic bias in the bank's favour that no line of code would have
-- to state out loud. |balance| is rounded; the sign picks the account.
--
-- NOBODY EATS A RESIDUAL PENNY HERE, AND THAT IS NOT A CONTRADICTION.
-- §12.3's residual is a real penny that must land SOMEWHERE, because the
-- shares have to sum to a source. §12.2 has no residual to place: the
-- sub-cent fraction never existed as money, no party was ever credited
-- with it, and the entry is two equal and opposite lines summing to
-- zero. This is also why §12.6's dust clearing (2900) is NOT engaged --
-- 2900 exists for dust that arrived as a real external amount, such as a
-- USDC transfer with six decimals, where truncating would break the
-- identity between customer balances and our obligation. A fraction of a
-- cent of interest is not money that arrived; it is precision that was
-- never claimed. The bound is half a cent per account per day, it is
-- unbiased by construction, and it is disclosed.
--
-- The residual penny placed ACROSS DAYS is 0020's, and it stays 0020's.
-- There are still exactly two rounding rules in this ledger, they are
-- the two DESIGN §12 already had, and each accrual product uses the one
-- whose precondition it actually meets.
--
-- ---------------------------------------------------------------------
-- 4.  DAY COUNT: ACT/365 FIXED, AND WHY IT IS DEFENSIBLE
-- ---------------------------------------------------------------------
--
-- A rate is per annum; a day is a fraction of a year; the convention is
-- which fraction. Stated, because "the usual one" is not an answer.
--
-- ACT/365 FIXED: the numerator is the actual number of days (here always
-- 1 -- this is a DAILY accrual, so each posting is one day) and the
-- denominator is 365, in every year, leap or not.
--
--   * It is the US deposit convention. 12 CFR 1030 (Reg DD) Appendix A
--     computes the daily periodic rate as the nominal annual rate
--     divided by 365. A deposit product whose disclosed APY is computed
--     on /365 and whose ledger accrues on /360 discloses one number and
--     charges another.
--
--   * ACT/360 -- the money-market and commercial-lending convention --
--     pays and charges 365/360 = 1.389% MORE per year for the same
--     quoted rate. That is defensible on a commercial loan quoted that
--     way and indefensible on a consumer-facing deposit disclosure. We
--     are a business current account and both sides are disclosed, so
--     both sides get /365.
--
--   * FIXED rather than ACT/ACT: in a leap year the 366th day accrues at
--     1/365, so a leap year pays 366/365 of the nominal rate. The
--     alternative changes the denominator mid-product, which means two
--     statements a year apart divide by different numbers for no reason
--     a customer can see. The over-accrual is 0.27% of the interest, it
--     is in the customer's favour on a credit balance and against them
--     on an overdraft, and it is written down here.
--
-- The denominator is a COLUMN on the rate policy, not a constant, so the
-- convention is data that a row can state and a reviewer can read --
-- constrained to (360, 365) so it cannot become a typo.
--
-- ---------------------------------------------------------------------
-- 5.  RATES ARE CONFIGURATION, EFFECTIVE-DATED, AND CANNOT REACH BACK
-- ---------------------------------------------------------------------
--
-- `approval_policy` (0001 §12) and `funds_availability_policy` (0001 §5)
-- are the pattern: a policy is a fact with a lifespan, it lives in its
-- own versioned table, it is append-only, and a change is a NEW ROW with
-- a later effective_from. `interest_rate_policy` is the third of them
-- and is built the same way, with one addition those two do not have.
--
-- THE ADDITION: a new policy row's effective_from must be strictly
-- LATER than every existing row for its tier AND strictly later than
-- every date already accrued under it. So "a rate change must not
-- retroactively re-price yesterday" is not a convention that a careful
-- operator observes -- it is a trigger that refuses the INSERT.
--
-- Resolution is `the greatest effective_from <= the accrual date`, so a
-- day accrued last week resolves to last week's rate forever, including
-- when the tick replays that date. `v_interest_rate_drift` asks the same
-- question of every posting already on the book and must return zero
-- rows; it is the invariant that would catch a policy row inserted
-- behind the trigger's back.
--
-- THE RATE IS ON THE RATE CARD, NOT ON THE ENROLMENT. A schedule cites a
-- TIER ('standard'), not a rate. One new policy row re-prices every
-- enrolled account from a date forward; putting the rate on the schedule
-- would mean N new schedule rows per rate change and N chances to write
-- a different number on one of them.
--
-- ---------------------------------------------------------------------
-- 6.  THE BASIS IS THE SETTLED LEDGER BALANCE, AT A RECORDED WATERMARK
-- ---------------------------------------------------------------------
--
-- Interest is priced on `ledger_settled_cents(account, accrual_date,
-- observed_booking_seq)` from 0022 -- THE canonical bitemporal balance
-- in this system, not a fourth private copy of one. Both predicates are
-- load-bearing:
--
--   value_date  <= the accrual date    what the ledger says about that
--                                      business day
--   booking_seq <= the watermark       what we had LEARNED when we
--                                      priced it
--
-- Not the AVAILABLE balance. Available subtracts holds, and a hold is
-- money we have not yet been asked for -- the customer still holds the
-- funds and we still owe them, so we still owe interest on them. A card
-- authorisation is not a withdrawal.
--
-- THE WATERMARK IS STORED, and that is a bitemporal decision with a
-- consequence. A correction backdated into a day that has already been
-- priced does NOT re-price that day: the posting stands, the row records
-- exactly which watermark it was priced at, and the number remains
-- reproducible from the row. Re-pricing would mean reversing and
-- re-booking an interest charge that was correct on the information
-- available -- which is a real product (an interest adjustment) and is
-- named as a gap in docs/ACCRUAL.md rather than half-built here.
--
-- `assert_interest_posting()` RE-DERIVES THE BASIS from the account, the
-- date and the stored watermark and refuses a row that disagrees, so the
-- balance on the row is not trusted either. TypeScript computes,
-- Postgres verifies -- 0020's bargain, kept.
-- =====================================================================


