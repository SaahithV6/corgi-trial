-- An enrolment is only meaningful on a customer deposit leaf. Written as
-- a trigger because a CHECK cannot subquery, and checked at ENROLMENT
-- rather than at every day: an account that is not a deposit leaf is a
-- mistake somebody made once, not a condition that changes nightly.
CREATE FUNCTION assert_interest_schedule() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_acct account%ROWTYPE;
BEGIN
  SELECT * INTO v_acct FROM account WHERE id = NEW.account_id;

  IF v_acct.code <> '2100' OR v_acct.business_id IS NULL THEN
    RAISE EXCEPTION
      'account % is %/% -- interest accrues on a customer deposit leaf (2100 with a business), nothing else',
      NEW.account_id, v_acct.code, COALESCE(v_acct.business_id::text, 'house')
      USING ERRCODE = '55006';
  END IF;

  IF v_acct.closed_at IS NOT NULL THEN
    RAISE EXCEPTION 'account % was closed at %; a closed account accrues nothing',
      NEW.account_id, v_acct.closed_at USING ERRCODE = '55006';
  END IF;

  IF v_acct.book::text <> 'financial' THEN
    RAISE EXCEPTION 'account % is in the % book; interest is real money',
      NEW.account_id, v_acct.book USING ERRCODE = '55006';
  END IF;

  -- An enrolment that starts before the rate card does would produce
  -- days with no resolvable rate, which would fail one at a time at the
  -- posting trigger instead of once, here, where it can be fixed.
  IF (interest_rate_at(NEW.rate_tier, NEW.start_date)).id IS NULL THEN
    RAISE EXCEPTION
      'rate card % has no row effective on or before %, so the first day of this enrolment could not be priced',
      NEW.rate_tier, NEW.start_date USING ERRCODE = '55006';
  END IF;

  RETURN NEW;
END $$;

