-- ---------------------------------------------------------------------
-- 12.  The claim -- at most once, by unique index
-- ---------------------------------------------------------------------
--
-- 0020 §9's construction, deliberately identical, because the
-- requirement is identical. The key is spelt `interest:` rather than
-- `accrual:` so that an interest day and a fee day for the same account
-- on the same date can never collide in journal_entry.idempotency_key --
-- and so that a human reading a key knows which product wrote it.

CREATE TABLE interest_day (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  schedule_id     uuid NOT NULL REFERENCES interest_schedule(id),

  -- THE BUSINESS DATE THIS IS INTEREST FOR. Not the date the job ran. It
  -- becomes the journal entry's value_date and the lifecycle trigger
  -- refuses any entry that says otherwise.
  accrual_date    date NOT NULL,

  -- Generated, from the two source facts and nothing else. The date is
  -- assembled from EXTRACTed integers rather than to_char(), because
  -- every textual rendering of a date is only STABLE (DateStyle is a
  -- session GUC) and a generated column's expression must be IMMUTABLE.
  -- A key that depends on a session setting is a key that silently
  -- becomes a different key, which is the exact shape of a double post.
  idempotency_key text GENERATED ALWAYS AS (
    'interest:' || schedule_id::text || ':'
      || lpad(EXTRACT(YEAR  FROM accrual_date)::int::text, 4, '0') || '-'
      || lpad(EXTRACT(MONTH FROM accrual_date)::int::text, 2, '0') || '-'
      || lpad(EXTRACT(DAY   FROM accrual_date)::int::text, 2, '0')
  ) STORED,

  claimed_at      timestamptz NOT NULL DEFAULT now(),
  claimed_by      text NOT NULL CHECK (length(btrim(claimed_by)) > 0),

  CONSTRAINT interest_day_once     UNIQUE (schedule_id, accrual_date),
  CONSTRAINT interest_day_key_once UNIQUE (idempotency_key)
);

CREATE INDEX interest_day_date_idx ON interest_day (accrual_date DESC, schedule_id);

COMMENT ON COLUMN interest_day.idempotency_key IS
  'GENERATED ALWAYS from the schedule and the date -- source facts, never a uuid the job made up. Handed to postEntry(), where journal_entry.idempotency_key is UNIQUE in turn.';


CREATE FUNCTION assert_interest_day() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_sched interest_schedule%ROWTYPE;
BEGIN
  SELECT * INTO v_sched FROM interest_schedule WHERE id = NEW.schedule_id;

  IF NEW.accrual_date < v_sched.start_date
     OR (v_sched.end_date IS NOT NULL AND NEW.accrual_date > v_sched.end_date) THEN
    RAISE EXCEPTION
      'enrolment % runs % .. %; % is outside it and can never accrue',
      NEW.schedule_id, v_sched.start_date,
      COALESCE(v_sched.end_date::text, 'open'), NEW.accrual_date
      USING ERRCODE = '55006';
  END IF;

  RETURN NEW;
END $$;

