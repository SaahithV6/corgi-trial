-- The screen's row source: one row per claimed day, decided or not, with
-- the whole working and the entry it cites.
CREATE VIEW v_interest_daily AS
SELECT d.id                    AS interest_day_id,
       d.schedule_id,
       s.account_id,
       a.business_id,
       b.legal_name            AS business_name,
       a.name                  AS account_name,
       s.rate_tier,
       d.accrual_date,
       d.idempotency_key,
       d.claimed_at,
       d.claimed_by,
       ip.disposition,
       ip.side,
       ip.policy_id,
       p.effective_from        AS policy_effective_from,
       ip.basis_balance_cents,
       ip.observed_booking_seq,
       ip.rate_bps,
       ip.day_count,
       ip.numerator,
       ip.denominator,
       ip.whole_cents,
       ip.remainder_units,
       ip.rounding,
       ip.amount_cents,
       -- The SIGNED effect on the customer's deposit account, which is
       -- the number they actually care about: negative is a debit.
       CASE ip.side
         WHEN 'credit'    THEN  ip.amount_cents
         WHEN 'overdraft' THEN -ip.amount_cents
         ELSE 0::bigint
       END                     AS customer_effect_cents,
       ip.entry_id,
       ip.skip_reason,
       ip.decided_at,
       ip.decided_by_run
  FROM interest_day d
  JOIN interest_schedule s ON s.id = d.schedule_id
  JOIN account a           ON a.id = s.account_id
  LEFT JOIN business b     ON b.id = a.business_id
  LEFT JOIN interest_posting ip ON ip.interest_day_id = d.id
  LEFT JOIN interest_rate_policy p ON p.id = ip.policy_id;

COMMENT ON VIEW v_interest_daily IS
  'One row per claimed interest day with the complete working: the balance, the watermark it was read at, the rate, the day count, the fraction as two integers, the rounding direction and the cents.';


-- One row per (enrolment, month): how many days, how much was paid, how
-- much was charged, and how many days each rounding direction took.
-- There is deliberately NO target column here and no month_drift view to
-- go with it -- daily interest has no monthly total to sum back to, and
-- inventing one would be pretending §12.3 applies.
CREATE VIEW v_interest_month AS
SELECT s.id                                                   AS schedule_id,
       s.account_id,
       a.business_id,
       s.rate_tier,
       date_trunc('month', d.accrual_date::timestamp)::date    AS month_start,
       count(*)                                               AS days_claimed,
       count(ip.*)                                            AS days_decided,
       count(*) FILTER (WHERE ip.disposition = 'posted')       AS days_posted,
       count(*) FILTER (WHERE ip.disposition = 'skipped')      AS days_skipped,
       count(*) FILTER (WHERE ip.side = 'credit')              AS days_credit,
       count(*) FILTER (WHERE ip.side = 'overdraft')           AS days_overdraft,
       count(*) FILTER (WHERE ip.rounding = 'up')              AS days_rounded_up,
       count(*) FILTER (WHERE ip.rounding = 'down')            AS days_rounded_down,
       count(*) FILTER (WHERE ip.rounding = 'tie_to_even')     AS days_tie_to_even,
       count(*) FILTER (WHERE ip.rounding = 'exact')           AS days_exact,
       COALESCE(SUM(ip.amount_cents) FILTER (WHERE ip.side = 'credit'), 0)
                                                              AS credit_interest_cents,
       COALESCE(SUM(ip.amount_cents) FILTER (WHERE ip.side = 'overdraft'), 0)
                                                              AS overdraft_interest_cents,
       min(ip.basis_balance_cents)                            AS min_basis_cents,
       max(ip.basis_balance_cents)                            AS max_basis_cents
  FROM interest_day d
  JOIN interest_schedule s ON s.id = d.schedule_id
  JOIN account a           ON a.id = s.account_id
  LEFT JOIN interest_posting ip ON ip.interest_day_id = d.id
 GROUP BY s.id, s.account_id, a.business_id, s.rate_tier,
          date_trunc('month', d.accrual_date::timestamp);


-- MUST BE EMPTY. A posting whose journal entry is not the entry that
-- posting describes: wrong value date, wrong amount on the customer's
-- account, or the wrong side of the chart.
--
-- The lifecycle trigger refuses all of this at insert, so a row here
-- means the trigger is gone -- or that somebody edited a money row,
-- which the privileges say they cannot. IT CAN FAIL: dropping
-- interest_posting_lifecycle and inserting a posting against an entry
-- with a different value date produces a row, which was checked against
-- this database inside a transaction that was rolled back.
CREATE VIEW v_interest_ledger_drift AS
SELECT ip.interest_day_id,
       d.accrual_date,
       d.idempotency_key,
       e.id             AS entry_id,
       e.value_date,
       ip.side,
       ip.amount_cents,
       COALESCE(SUM(l.amount_cents) FILTER (WHERE l.account_id = s.account_id), 0) AS deposit_cents,
       COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '4400'), 0)             AS income_cents,
       COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '5400'), 0)             AS expense_cents
  FROM interest_posting ip
  JOIN interest_day      d ON d.id = ip.interest_day_id
  JOIN interest_schedule s ON s.id = d.schedule_id
  JOIN journal_entry     e ON e.id = ip.entry_id
  JOIN journal_line      l ON l.entry_id = e.id
  JOIN account           a ON a.id = l.account_id
 WHERE ip.disposition = 'posted'
 GROUP BY ip.interest_day_id, d.accrual_date, d.idempotency_key,
          e.id, e.value_date, ip.side, ip.amount_cents, s.account_id
HAVING e.value_date <> d.accrual_date
    OR COALESCE(SUM(l.amount_cents) FILTER (WHERE l.account_id = s.account_id), 0)
         <> CASE ip.side WHEN 'overdraft' THEN ip.amount_cents ELSE -ip.amount_cents END
    OR COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '4400'), 0)
         <> CASE ip.side WHEN 'overdraft' THEN -ip.amount_cents ELSE 0::bigint END
    OR COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '5400'), 0)
         <> CASE ip.side WHEN 'credit'    THEN  ip.amount_cents ELSE 0::bigint END;

COMMENT ON VIEW v_interest_ledger_drift IS
  'Must be empty. The posting, its value date and the two lines of its journal entry must agree, on the correct side of the chart. assert_interest_posting() refuses otherwise at insert.';


-- MUST BE EMPTY. A posting whose rate is not what the rate card says
-- applied on its accrual date.
--
-- THIS IS "A RATE CHANGE MUST NOT RETROACTIVELY RE-PRICE YESTERDAY",
-- asked of the whole book at any moment. The forward-only trigger on
-- interest_rate_policy makes the offending INSERT impossible; this view
-- is what would catch it if that trigger were dropped, and it can fail:
-- disabling the trigger and inserting a backdated policy row makes every
-- posting on or after that date appear here. Checked against this
-- database, in a transaction that was rolled back.
CREATE VIEW v_interest_rate_drift AS
SELECT ip.interest_day_id,
       d.accrual_date,
       s.rate_tier,
       ip.policy_id       AS posted_policy_id,
       p.id               AS resolved_policy_id,
       p.effective_from   AS resolved_effective_from,
       ip.side,
       ip.rate_bps        AS posted_rate_bps,
       CASE ip.side
         WHEN 'credit'    THEN p.credit_rate_bps
         WHEN 'overdraft' THEN p.overdraft_rate_bps
         ELSE 0
       END                AS resolved_rate_bps,
       ip.day_count       AS posted_day_count,
       p.day_count_denominator AS resolved_day_count
  FROM interest_posting ip
  JOIN interest_day      d ON d.id = ip.interest_day_id
  JOIN interest_schedule s ON s.id = d.schedule_id
  LEFT JOIN LATERAL (SELECT * FROM interest_rate_at(s.rate_tier, d.accrual_date)) p ON true
 WHERE p.id IS NULL
    OR ip.policy_id <> p.id
    OR ip.day_count <> p.day_count_denominator
    OR ip.rate_bps <> CASE ip.side
                        WHEN 'credit'    THEN p.credit_rate_bps
                        WHEN 'overdraft' THEN p.overdraft_rate_bps
                        ELSE 0
                      END;

COMMENT ON VIEW v_interest_rate_drift IS
  'Must be empty. Every posting must still resolve to the rate card row that was effective on its accrual date. A row here means a policy was backdated and days already on the ledger have been re-priced underneath.';


-- Claimed and never decided: a tick took the day and did not finish.
-- Safe -- nothing posted -- but never invisible.
CREATE VIEW v_interest_unresolved AS
SELECT d.id AS interest_day_id, d.schedule_id, d.accrual_date,
       d.idempotency_key, d.claimed_at, d.claimed_by,
       s.account_id, s.rate_tier
  FROM interest_day d
  JOIN interest_schedule s ON s.id = d.schedule_id
  LEFT JOIN interest_posting ip ON ip.interest_day_id = d.id
 WHERE ip.interest_day_id IS NULL;


-- Days an enrolment owes that nothing has claimed, up to the BOOK day.
--
-- book_date(now()) and not CURRENT_DATE, which is 0023's correction to
-- v_accrual_gap learned the first time rather than the second:
-- CURRENT_DATE resolves against the session TimeZone (UTC on Neon), so
-- between 20:00 and midnight Eastern it is already on tomorrow and would
-- report every enrolment as owing a day that has not happened.
CREATE VIEW v_interest_gap AS
SELECT s.id AS schedule_id, s.account_id, s.rate_tier, d AS missing_date
  FROM interest_schedule s
  CROSS JOIN LATERAL interest_due_dates(
    s.id, s.start_date, LEAST(COALESCE(s.end_date, book_date(now())), book_date(now()))
  ) AS d;

COMMENT ON VIEW v_interest_gap IS
  'Dates an enrolment owes and nothing has claimed, bounded by the BOOK day. Persistently non-empty means the tick is not running.';


-- The rate card as a screen reads it: every version, with the window it
-- was (or is) in force for. `superseded_on` is the next version's
-- effective date, so "which rate applied on 9 September" is answerable
-- by eye and not only by the resolution function.
CREATE VIEW v_interest_rate_card AS
SELECT p.id,
       p.tier,
       t.description       AS tier_description,
       p.effective_from,
       LEAD(p.effective_from) OVER (PARTITION BY p.tier ORDER BY p.effective_from)
                           AS superseded_on,
       p.credit_rate_bps,
       p.overdraft_rate_bps,
       p.day_count_denominator,
       p.note,
       p.created_at,
       (SELECT count(*) FROM interest_posting ip WHERE ip.policy_id = p.id) AS days_priced
  FROM interest_rate_policy p
  JOIN interest_rate_tier t ON t.tier = p.tier;


-- ---------------------------------------------------------------------
-- 17.  Append-only, in two layers
-- ---------------------------------------------------------------------
--
-- No journal line is written by anything in this file -- postEntry()
-- does that -- so these are not money tables. They are the AUDIT of
-- money movement plus the policy it was priced by, and an audit trail
-- you can UPDATE is a story. 0012 §12 and 0020 §14's treatment,
-- unchanged: no UPDATE/DELETE grant, and 0001's ledger_row_is_immutable()
-- as the second layer that also binds the owner.
--
-- interest_rate_policy is in the list for the reason the rest of this
-- migration is about: a rate you can edit in place is a rate that can
-- re-price the past, and the whole of §5 is an argument that it must not
-- be able to.

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['interest_rate_tier', 'interest_rate_policy',
                           'interest_schedule', 'interest_day', 'interest_posting'] LOOP
    EXECUTE format(
      'CREATE TRIGGER %I_no_update_delete BEFORE UPDATE OR DELETE ON %I
         FOR EACH ROW EXECUTE FUNCTION ledger_row_is_immutable()', t, t);
    EXECUTE format(
      'CREATE TRIGGER %I_no_truncate BEFORE TRUNCATE ON %I
         FOR EACH STATEMENT EXECUTE FUNCTION ledger_row_is_immutable()', t, t);
  END LOOP;
END $$;

