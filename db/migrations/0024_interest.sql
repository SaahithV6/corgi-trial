-- ---------------------------------------------------------------------
-- 18.  The rate card, and the enrolments, for the accounts that exist
-- ---------------------------------------------------------------------
--
-- TWO POLICY VERSIONS, seeded in ascending order so the forward-only
-- trigger accepts both, because ONE version could not demonstrate the
-- thing §5 is about. With two, the same account on two adjacent business
-- dates is priced by two different rows, and re-running the earlier date
-- still resolves the earlier row.
--
--   v1   book_date - 4    credit 150 bps   overdraft 1800 bps   /365
--   v2   book_date - 2    credit 125 bps   overdraft 1800 bps   /365
--
-- THE CREDIT RATE IS CUT AND THE OVERDRAFT RATE IS NOT. That is the
-- realistic direction and it is also the one a customer notices, which
-- is the point of being able to prove that the cut did not reach back.
--
-- THE OVERDRAFT RATE IS ON THE CARD AND HAS PRICED NOTHING. No deposit
-- leaf on this book has been in debit on any value date -- measured, §1
-- -- so 4400 will carry a zero balance until one is. That is the honest
-- state of this feature and the screen says so on its face rather than
-- an overdraft being manufactured to photograph.
--
-- Dates are relative to the book day rather than hard-coded, so the same
-- shape appears whenever this migration is applied, including after a
-- db:reset. Idempotent by NOT EXISTS rather than by ON CONFLICT, so the
-- forward-only trigger never fires on a re-run at all.

INSERT INTO interest_rate_tier (tier, description)
VALUES ('standard',
        'The standard business current account rate card: what we pay on a credit balance and what we charge on an arranged overdraft, both ACT/365 fixed.')
ON CONFLICT (tier) DO NOTHING;

