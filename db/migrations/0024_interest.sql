-- ---------------------------------------------------------------------
-- 14.  The row lock, without the UPDATE privilege
-- ---------------------------------------------------------------------
--
-- 0008's, 0012's and 0020's construction. corgi_app holds no UPDATE on
-- interest_schedule and must not, so it cannot write FOR UPDATE itself.
-- Taken in the CALLER's transaction, released at the caller's COMMIT.
--
-- It serialises two ticks that want the same enrolment. It is NOT what
-- makes the job exactly-once -- the unique indexes are -- and the
-- difference matters, because a crashed process releases a lock and
-- cannot release a unique index.

CREATE FUNCTION lock_interest_schedule(p_schedule uuid)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_id uuid;
BEGIN
  SELECT s.id INTO v_id FROM interest_schedule s WHERE s.id = p_schedule FOR UPDATE;
  RETURN v_id IS NOT NULL;
END $$;

ALTER FUNCTION lock_interest_schedule(uuid) SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION lock_interest_schedule(uuid) FROM PUBLIC;


-- ---------------------------------------------------------------------
-- 15.  What is owed: the calendar, in ONE place
-- ---------------------------------------------------------------------
--
-- 0012 §8 and 0020 §12's rule, applied again: no date arithmetic in
-- TypeScript. The set of dates an enrolment owes is a SQL function, the
-- tick asks it, and there is no second implementation of "which days are
-- in the window" to drift from this one.

CREATE FUNCTION interest_due_dates(p_schedule uuid, p_from date, p_to date)
RETURNS SETOF date
LANGUAGE sql STABLE AS $$
  SELECT d::date
    FROM interest_schedule s,
         generate_series(
           GREATEST(s.start_date, p_from)::timestamp,
           LEAST(COALESCE(s.end_date, p_to), p_to)::timestamp,
           interval '1 day'
         ) AS d
   WHERE s.id = p_schedule
     AND NOT EXISTS (
           SELECT 1 FROM interest_day id2
            WHERE id2.schedule_id = s.id AND id2.accrual_date = d::date
         )
   ORDER BY 1
$$;

ALTER FUNCTION interest_due_dates(uuid, date, date) SET search_path = public, pg_temp;

COMMENT ON FUNCTION interest_due_dates(uuid, date, date) IS
  'The only definition of which dates an interest enrolment still owes. The tick asks it; nothing in TypeScript computes a date range.';


