-- ---------------------------------------------------------------------
-- 13.  The outcome -- one per claimed day, with the whole sum shown
-- ---------------------------------------------------------------------
--
-- "A number a customer cannot reproduce by hand is a number they will
-- dispute." So the row carries the hand calculation and not just its
-- answer: the balance it was priced on, the watermark that balance was
-- read at, the rate, the day-count denominator, the exact fraction as
-- its two integers, the quotient, the remainder, which way it rounded,
-- and the cents posted.

CREATE TABLE interest_posting (
  interest_day_id      uuid PRIMARY KEY REFERENCES interest_day(id),
  disposition          accrual_disposition NOT NULL,   -- 0020's enum, reused

  -- ---- which side, and which rate card row priced it ----------------
  side                 interest_side NOT NULL,
  policy_id            uuid NOT NULL REFERENCES interest_rate_policy(id),

  -- ---- the basis, and the instant it was true at --------------------
  -- SIGNED: negative is an overdrawn customer. The magnitude goes into
  -- the arithmetic; the sign picks the side and therefore the accounts.
  basis_balance_cents  bigint NOT NULL,
  -- The booking watermark the balance was read at. WITHOUT THIS the
  -- figure is not reproducible: the settled balance of a past value date
  -- changes as later corrections are booked into it, so "the balance on
  -- 9 September" is only an answer once you say when you asked.
  observed_booking_seq bigint NOT NULL CHECK (observed_booking_seq >= 0),

  -- ---- the price of a day -------------------------------------------
  rate_bps             integer NOT NULL CHECK (rate_bps BETWEEN 0 AND 10000),
  day_count            integer NOT NULL CHECK (day_count IN (360, 365)),

  -- ---- the exact fraction, as the two integers it actually is -------
  numerator            bigint NOT NULL CHECK (numerator >= 0),
  denominator          bigint NOT NULL CHECK (denominator > 0),
  whole_cents          bigint NOT NULL CHECK (whole_cents >= 0),
  remainder_units      bigint NOT NULL CHECK (remainder_units >= 0),
  rounding             interest_rounding NOT NULL,

  -- The magnitude posted. The side says who pays whom.
  amount_cents         bigint NOT NULL CHECK (amount_cents >= 0),

  entry_id             uuid REFERENCES journal_entry(id),
  skip_reason          text,

  decided_at           timestamptz NOT NULL DEFAULT now(),
  decided_by_run       text NOT NULL CHECK (length(btrim(decided_by_run)) > 0),

  -- =================================================================
  -- THE ARITHMETIC, RE-DERIVED BY THE DATABASE ON EVERY INSERT.
  --
  -- Eight relations over four inputs (balance, rate, day count, and the
  -- sign of the balance). A row that disagrees with
  -- interest_round_half_even() by one cent cannot be stored, so the
  -- figures the screen renders are not a claim ABOUT the arithmetic --
  -- they ARE the arithmetic, checked by the thing that persisted them.
  --
  -- The last conjunct restates the rounding rule inline rather than
  -- delegating to the function a second time. It is deliberately
  -- redundant: if someone ever "optimises" interest_round_half_even into
  -- half-up, this line disagrees and no row can be written at all.
  -- =================================================================
  CONSTRAINT interest_posting_arithmetic CHECK (
        denominator     = interest_denominator(day_count)
    AND numerator       = interest_numerator(basis_balance_cents, rate_bps)
    AND whole_cents     = numerator / denominator
    AND remainder_units = numerator % denominator
    AND rounding        = interest_rounding_of(numerator, denominator)
    AND amount_cents    = interest_daily_cents(basis_balance_cents, rate_bps, day_count)
    AND side            = interest_side_of(basis_balance_cents)
    AND amount_cents    = whole_cents + CASE
                            WHEN 2 * remainder_units > denominator THEN 1
                            WHEN 2 * remainder_units < denominator THEN 0
                            ELSE whole_cents % 2
                          END
  ),

  -- A posted day has an entry, a non-zero amount and a real side; a
  -- skipped day has none of those and says why. There is no third shape.
  -- A 'flat' day -- a deposit account at exactly zero -- can only ever
  -- be skipped, which falls out of amount_cents = 0 rather than needing
  -- its own clause.
  CONSTRAINT interest_posting_shape CHECK (
       (disposition = 'posted'
          AND entry_id IS NOT NULL AND skip_reason IS NULL
          AND amount_cents > 0 AND side <> 'flat')
    OR (disposition = 'skipped'
          AND entry_id IS NULL AND skip_reason IS NOT NULL
          AND amount_cents = 0)
  )
);

CREATE INDEX interest_posting_entry_idx ON interest_posting (entry_id) WHERE entry_id IS NOT NULL;
CREATE INDEX interest_posting_side_idx  ON interest_posting (side);

COMMENT ON TABLE interest_posting IS
  'One decision per claimed day, by PRIMARY KEY. Carries the complete working -- balance, watermark, rate, day count, the exact fraction as two integers, the quotient, the remainder, the rounding direction and the cents -- so a customer can reproduce the number by hand from the row.';
COMMENT ON COLUMN interest_posting.observed_booking_seq IS
  'The booking watermark the basis balance was read at. The number is only reproducible with it: a backdated correction changes what the settled balance of a past value date is, and this says which answer was priced.';
COMMENT ON CONSTRAINT interest_posting_arithmetic ON interest_posting IS
  'Re-derives all eight relations from the balance, the rate and the day count, and restates the half-even tiebreak inline so that a change to the function alone cannot pass. TypeScript computes, Postgres verifies.';


-- The lifecycle gate. 0020 §10's instinct: the claims that would be
-- catastrophic if they were merely conventional.
CREATE FUNCTION assert_interest_posting() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_day      interest_day%ROWTYPE;
  v_sched    interest_schedule%ROWTYPE;
  v_policy   interest_rate_policy%ROWTYPE;
  v_entry    journal_entry%ROWTYPE;
  v_basis    bigint;
  v_expected integer;
  v_deposit  bigint;
  v_income   bigint;
  v_expense  bigint;
  v_lines    int;
BEGIN
  SELECT * INTO v_day   FROM interest_day      WHERE id = NEW.interest_day_id;
  SELECT * INTO v_sched FROM interest_schedule WHERE id = v_day.schedule_id;

  -- ---- the rate card row that priced it -----------------------------
  --
  -- THIS is "a rate change must not retroactively re-price yesterday",
  -- enforced at the moment the row is written. The policy is resolved
  -- from the tier and THE ACCRUAL DATE, so a replay of an old date
  -- resolves the old rate and a posting that cites any other row is
  -- refused.
  v_policy := interest_rate_at(v_sched.rate_tier, v_day.accrual_date);

  IF v_policy.id IS NULL THEN
    RAISE EXCEPTION 'rate card % has no row effective on or before %',
      v_sched.rate_tier, v_day.accrual_date USING ERRCODE = '55006';
  END IF;

  IF NEW.policy_id IS DISTINCT FROM v_policy.id THEN
    RAISE EXCEPTION
      'posting cites rate policy %, but % on % resolves to % (effective %)',
      NEW.policy_id, v_sched.rate_tier, v_day.accrual_date,
      v_policy.id, v_policy.effective_from USING ERRCODE = '42501';
  END IF;

  IF NEW.day_count IS DISTINCT FROM v_policy.day_count_denominator THEN
    RAISE EXCEPTION 'posting uses a /% day count but policy % is /%',
      NEW.day_count, v_policy.id, v_policy.day_count_denominator
      USING ERRCODE = '42501';
  END IF;

  v_expected := CASE NEW.side
                  WHEN 'credit'    THEN v_policy.credit_rate_bps
                  WHEN 'overdraft' THEN v_policy.overdraft_rate_bps
                  ELSE 0
                END;

  IF NEW.rate_bps IS DISTINCT FROM v_expected THEN
    RAISE EXCEPTION
      'posting prices the % side at % bps but policy % says % bps',
      NEW.side, NEW.rate_bps, v_policy.id, v_expected USING ERRCODE = '42501';
  END IF;

  -- ---- the basis, re-derived rather than believed --------------------
  --
  -- 0022's ledger_settled_cents IS the balance definition in this
  -- system. Asking it again here means the stored basis is a figure the
  -- database agrees with, not a figure the job asserted.
  v_basis := ledger_settled_cents(v_sched.account_id, v_day.accrual_date, NEW.observed_booking_seq);

  IF NEW.basis_balance_cents IS DISTINCT FROM v_basis THEN
    RAISE EXCEPTION
      'posting prices a balance of %c on % at watermark %, but the ledger says %c',
      NEW.basis_balance_cents, v_day.accrual_date, NEW.observed_booking_seq, v_basis
      USING ERRCODE = '42501';
  END IF;

  IF NEW.disposition::text = 'skipped' THEN
    RETURN NEW;
  END IF;

  -- ---- the journal entry IS this accrual -----------------------------
  SELECT * INTO v_entry FROM journal_entry WHERE id = NEW.entry_id;
  IF v_entry.id IS NULL THEN
    RAISE EXCEPTION 'posting for day % cites entry % which does not exist',
      NEW.interest_day_id, NEW.entry_id USING ERRCODE = '55006';
  END IF;

  -- The one that makes this exactly-once rather than merely careful.
  IF v_entry.idempotency_key IS DISTINCT FROM v_day.idempotency_key THEN
    RAISE EXCEPTION
      'day % derives key %, but entry % carries % -- these are not the same accrual',
      NEW.interest_day_id, v_day.idempotency_key, v_entry.id, v_entry.idempotency_key
      USING ERRCODE = '42501';
  END IF;

  -- VALUE DATE IS THE ACCRUAL DATE, NOT THE RUN DATE.
  IF v_entry.value_date IS DISTINCT FROM v_day.accrual_date THEN
    RAISE EXCEPTION
      'entry % has value date % but the interest is for % -- interest books at the date it accrued for',
      v_entry.id, v_entry.value_date, v_day.accrual_date USING ERRCODE = '42501';
  END IF;

  IF v_entry.book::text <> 'financial' THEN
    RAISE EXCEPTION 'entry % is in the % book; interest is real money',
      v_entry.id, v_entry.book USING ERRCODE = '42501';
  END IF;

  -- ---- and the entry must be the RIGHT SHAPE for its side ------------
  --
  -- credit    we PAY the customer:  deposit -amount (credit, we owe more)
  --                                 5400    +amount (debit, an expense)
  -- overdraft we CHARGE them:       deposit +amount (debit, we owe less)
  --                                 4400    -amount (credit, income)
  --
  -- Getting this backwards is the error chart.ts opens by warning about
  -- and the one that would show a customer their balance going UP every
  -- time we charged them overdraft interest.
  SELECT count(*),
         COALESCE(SUM(l.amount_cents) FILTER (WHERE l.account_id = v_sched.account_id), 0),
         COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '4400'), 0),
         COALESCE(SUM(l.amount_cents) FILTER (WHERE a.code = '5400'), 0)
    INTO v_lines, v_deposit, v_income, v_expense
    FROM journal_line l JOIN account a ON a.id = l.account_id
   WHERE l.entry_id = v_entry.id;

  IF NEW.side = 'credit' THEN
    IF v_lines <> 2 OR v_deposit <> -NEW.amount_cents
       OR v_expense <> NEW.amount_cents OR v_income <> 0 THEN
      RAISE EXCEPTION
        'entry % is not this credit-interest accrual: % lines, %c to the deposit account, %c to 5400, %c to 4400; expected 2, %c, %c and 0',
        v_entry.id, v_lines, v_deposit, v_expense, v_income,
        -NEW.amount_cents, NEW.amount_cents USING ERRCODE = '42501';
    END IF;
  ELSE
    IF v_lines <> 2 OR v_deposit <> NEW.amount_cents
       OR v_income <> -NEW.amount_cents OR v_expense <> 0 THEN
      RAISE EXCEPTION
        'entry % is not this overdraft-interest accrual: % lines, %c to the deposit account, %c to 4400, %c to 5400; expected 2, %c, %c and 0',
        v_entry.id, v_lines, v_deposit, v_income, v_expense,
        NEW.amount_cents, -NEW.amount_cents USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END $$;

