/**
 * The standing-order vocabulary, and the two decisions that are pure.
 *
 * Nothing in this file talks to a database. The exactly-once guarantee lives
 * in `db/migrations/0012_standing_orders.sql` — a UNIQUE constraint on
 * (standing order, scheduled date), a generated idempotency key, and a trigger
 * that refuses an outcome citing the wrong instruction. These are the types the
 * application uses to *talk about* that, plus the funding and freshness rules,
 * which are pure functions of numbers and dates and are unit-tested as such.
 *
 * Money is `bigint` minor units throughout. There is no `number` cents anywhere
 * below this line except in the screen's data contract, where the narrowing
 * happens once, in `screen.ts`.
 */

